// The pages and their default addresses (SPEC 5.3), for the pages table.
const PAGE_PATHS = {
  projects: '`/projects`',
  publications: '`/publications`',
  experience: '`/experience`',
  writing: '`/writing/`',
  contact: '`/contact`',
  meet: '`/meet` (with `booking`)',
  notFound: 'the "page not found" page',
};

const code = (value) => `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``;
const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(node) {
  if (node.enum) return node.enum.map(code).join(', ');
  if (node.anyOf) {
    const kinds = node.anyOf.map((option) => (option.type === 'integer' && node.anyOf.some((o) => o.pattern) ? null : typeOf(option)));
    if (node.anyOf.some((o) => o.pattern && /\\d\{4\}/.test(o.pattern))) return 'date';
    return [...new Set(kinds.filter(Boolean))].join(' or ');
  }
  if (node.pattern && /\\d\{4\}/.test(node.pattern)) return 'date';
  switch (node.type) {
    case 'string':
      return 'text';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return '`true` or `false`';
    case 'object':
      return 'block';
    case 'array': {
      const items = node.items ?? {};
      if (items.type === 'string' && !items.enum) return 'list of text';
      return 'list';
    }
    default:
      return 'value';
  }
}

/** The object form of a node (itself, or the object among its anyOf options). */
const objectOf = (node) => (node?.type === 'object' ? node : node?.anyOf?.find((option) => option.type === 'object'));

function rows(node, prefix, required = new Set(), out = []) {
  for (const [key, child] of Object.entries(node.properties ?? {})) {
    const path = prefix + key;
    if (SKIP.has(path)) continue;
    if (path === 'pages') {
      out.push({ path, child, required: false });
      continue; // the pages get their own table
    }
    out.push({ path, child, required: required.has(key) });
    const object = objectOf(child);
    if (object) rows(object, `${path}.`, new Set(object.required ?? []), out);
    const items = objectOf(child.items);
    if (items) rows(items, `${path}[].`, new Set(), out);
  }
  return out;
}

const describe = (path, child) => NOTES[path] ?? child.description;

export function reference() {
  const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'));
  const missing = [];
  const lines = ['| Field | Value | Default | What it does |', '|---|---|---|---|'];
  for (const { path, child } of rows(schema, '')) {
    const text = describe(path, child);
    if (!text) missing.push(path);
    const fallback = child.default !== undefined && !(typeof child.default === 'object' && Object.keys(child.default).length === 0);
    lines.push(`| \`${path}\` | ${cell(typeOf(child))} | ${fallback ? cell(code(child.default)) : ''} | ${cell(text ?? '')} |`);
  }

  const pages = schema.properties.pages.properties;
  const optionsOf = (page) => Object.keys(objectOf(page)?.properties ?? {});
  lines.push('', '<a id="page-options"></a>', '', '| Page | Default address |', '|---|---|');
  for (const [key, page] of Object.entries(pages)) {
    if (SKIP.has(`pages.${key}`)) continue;
    if (!PAGE_PATHS[key]) missing.push(`pages.${key}`);
    lines.push(`| \`pages.${key}\` | ${PAGE_PATHS[key] ?? ''} |`);
  }
  // Which options each page takes: most take them all; say which pages don't, or which only do.
  const shown = Object.entries(pages).filter(([key]) => !SKIP.has(`pages.${key}`));
  const all = [...new Set(shown.flatMap(([, page]) => optionsOf(page)))];
  const list = (items) => (items.length > 1 ? `${items.slice(0, -1).join(', ')} and ${items.at(-1)}` : items[0]);
  const named = all.map((option) => {
    const has = shown.filter(([, page]) => optionsOf(page).includes(option)).map(([key]) => `\`pages.${key}\``);
    const lacks = shown.filter(([, page]) => !optionsOf(page).includes(option)).map(([key]) => `\`pages.${key}\``);
    if (lacks.length === 0) return code(option);
    return has.length >= lacks.length ? `${code(option)} (not ${list(lacks)})` : `${code(option)} (${list(has)} only)`;
  });
  lines.push('', `Each page takes \`false\`, or a block with any of ${list(named)}.`);
  if (missing.length > 0) throw new Error(`site-yaml-reference: no words for ${missing.join(', ')}; add them to NOTES or PAGE_PATHS`);
  return `${START}\n\n${lines.join('\n')}\n\n${END}`;
}

export function current() {
  const text = readFileSync(DOC, 'utf8');
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a === -1 || b === -1) throw new Error(`docs/site-yaml.md has no ${START} … ${END} block`);
  return { text, a, b: b + END.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = reference();
  const { text, a, b } = current();
  const updated = text.slice(0, a) + fresh + text.slice(b);
  if (process.argv.includes('--check')) {
    if (updated !== text) {
      console.error('docs/site-yaml.md: the field reference is stale. Run `node tools/site-yaml-reference.mjs`.');
      process.exit(1);
    }
  } else {
    writeFileSync(DOC, updated);
    console.log('wrote the field reference in docs/site-yaml.md');
  }
}
